"""Generate the fixed-200 Hz attitude resampler FIR tables."""
import math
import sys


def blackman_harris(n):
    a = [0.35875, 0.48829, 0.14128, 0.01168]
    return [a[0] - a[1] * math.cos(2 * math.pi * i / (n - 1))
            + a[2] * math.cos(4 * math.pi * i / (n - 1))
            - a[3] * math.cos(6 * math.pi * i / (n - 1))
            for i in range(n)]


def fir(ntaps, fs, f_pass, f_stop):
    fc = (f_pass + f_stop) / 2.0 / fs
    mid = (ntaps - 1) / 2.0
    h = []
    for n, window in enumerate(blackman_harris(ntaps)):
        k = n - mid
        ideal = 2 * fc if k == 0 else math.sin(2 * math.pi * fc * k) / (math.pi * k)
        h.append(ideal * window)
    total = sum(h)
    return [value / total for value in h]


def response(h, fs, frequency):
    re = sum(c * math.cos(-2 * math.pi * frequency * n / fs) for n, c in enumerate(h))
    im = sum(c * math.sin(-2 * math.pi * frequency * n / fs) for n, c in enumerate(h))
    return math.hypot(re, im)


def worst_stop(h, fs, f_stop):
    worst = max(response(h, fs, f_stop + step * 0.5)
                for step in range(int((fs / 2 - f_stop) / 0.5) + 1))
    return 20 * math.log10(worst)


def emit(name, h, fs, f_stop):
    print(f"/* {name}: worst stopband {worst_stop(h, fs, f_stop):.1f} dB from {f_stop} Hz */")
    print(f"static const float {name}[{len(h)}] = {{ /* fs = {fs} Hz */")
    for i in range(0, len(h), 3):
        print("    " + ", ".join(f"{v:.9e}f" for v in h[i:i + 3]) + ",")
    print("};")


STAGES = {
    # A 2:1 stage accepts 0.20 Fs and attenuates the next fold band.
    "attitude_fir_half": (63, 1000, 200, 300),
    "attitude_fir_1k": (99, 1000, 25, 100),
    "attitude_fir_200": (99, 200, 25, 80),
}


if __name__ == "__main__":
    output = sys.stdout
    if len(sys.argv) == 2:
        output = open(sys.argv[1], "w", encoding="ascii", newline="\n")
        sys.stdout = output
    print("/* Generated by tests/design_attitude_filters.py - do not edit. */")
    print("#ifndef PROBE_ATTITUDE_FILTERS_H")
    print("#define PROBE_ATTITUDE_FILTERS_H")
    for name, (ntaps, fs, fp, fst) in STAGES.items():
        h = fir(ntaps, fs, fp, fst)
        assert worst_stop(h, fs, fst) <= -60.0
        emit(name, h, fs, fst)
    print("#endif")
    if output is not sys.stdout:
        output.close()
